export class FormulaInspectorUI {
  constructor(containerElement, tooltipElement) {
    this.container = containerElement;
    this.tooltip = tooltipElement;
    this.activeTermKey = 'thermal-pressurization';
    this.render();
  }

  render() {
    this.container.innerHTML = `
      <div class="math-equations-board glass-panel">
        <div class="board-header">
          <h3>Unified THM Governing Differential Equations</h3>
          <p class="subtitle">Hover over or tap any highlighted term to inspect its physical mechanism, units, and coupling pathway.</p>
        </div>

        <div class="equations-stack">
          <!-- Equation 1: Mechanical Momentum & Constitutive -->
          <div class="equation-row">
            <span class="eq-badge badge-m">1. Solid Momentum & Stress Equilibrium</span>
            <div class="eq-content">
              <span class="katex-item math-clickable" data-term="sigma-prime">\\nabla \\cdot \\boldsymbol{\\sigma}'</span>
              <span class="math-op">-</span>
              <span class="katex-item math-clickable" data-term="alpha-p">\\alpha \\nabla p</span>
              <span class="math-op">+</span>
              <span class="katex-plain">\\rho_{\\text{bulk}} \\mathbf{g} = 0</span>
            </div>
            <div class="eq-content secondary-eq">
              <span class="katex-plain">\\boldsymbol{\\sigma}' = \\mathbf{C} : \\boldsymbol{\\epsilon} - </span>
              <span class="katex-item math-clickable" data-term="thermal-stress">3K \\alpha_T (T - T_0) \\mathbf{I}</span>
            </div>
          </div>

          <!-- Equation 2: Fluid Mass & Storage -->
          <div class="equation-row">
            <span class="eq-badge badge-h">2. Fluid Mass Conservation & Flow</span>
            <div class="eq-content">
              <span class="katex-item math-clickable" data-term="storage-rate">S_s \\frac{\\partial p}{\\partial t}</span>
              <span class="math-op">+</span>
              <span class="katex-item math-clickable" data-term="strain-rate-coupling">\\alpha \\frac{\\partial \\epsilon_v}{\\partial t}</span>
              <span class="math-op">-</span>
              <span class="katex-item math-clickable" data-term="thermal-pressurization">\\beta_m \\frac{\\partial T}{\\partial t}</span>
              <span class="math-op">=</span>
              <span class="katex-item math-clickable" data-term="darcy-divergence">\\nabla \\cdot \\left[ \\frac{\\mathbf{k}}{\\mu_f(T)} (\\nabla p - \\rho_f \\mathbf{g}) \\right]</span>
              <span class="katex-plain">+ Q_f</span>
            </div>
          </div>

          <!-- Equation 3: Thermal Energy Balance -->
          <div class="equation-row">
            <span class="eq-badge badge-t">3. Energy Conservation & Heat Transport</span>
            <div class="eq-content">
              <span class="katex-plain">(\\rho C_p)_m \\frac{\\partial T}{\\partial t}</span>
              <span class="math-op">+</span>
              <span class="katex-item math-clickable" data-term="convective-heat">\\rho_f c_f \\mathbf{q}_d \\cdot \\nabla T</span>
              <span class="math-op">-</span>
              <span class="katex-item math-clickable" data-term="fourier-conduction">\\nabla \\cdot (\\boldsymbol{\\kappa}_m \\nabla T)</span>
              <span class="math-op">+</span>
              <span class="katex-item math-clickable" data-term="piezocaloric">T_0 \\beta_s K \\frac{\\partial \\epsilon_v}{\\partial t}</span>
              <span class="katex-plain">= Q_T</span>
            </div>
          </div>
        </div>

        <!-- Term Detail Inspector Card -->
        <div class="term-inspector-card" id="term-detail-box">
          <!-- Populated dynamically -->
        </div>
      </div>
    `;

    this.renderMathSymbols();
    this.bindHoverEvents();
    this.updateInspector(this.activeTermKey);
  }

  renderMathSymbols() {
    if (!window.katex) return;
    this.container.querySelectorAll('.katex-item, .katex-plain').forEach(el => {
      const tex = el.textContent.trim();
      try {
        window.katex.render(tex, el, { throwOnError: false, displayMode: false });
      } catch (err) {
        console.error("KaTeX parse error", err);
      }
    });
  }

  bindHoverEvents() {
    this.container.querySelectorAll('.math-clickable').forEach(el => {
      const termKey = el.getAttribute('data-term');
      el.addEventListener('mouseenter', () => {
        this.updateInspector(termKey);
      });
      el.addEventListener('click', () => {
        this.updateInspector(termKey);
      });
    });
  }

  updateInspector(termKey) {
    this.activeTermKey = termKey;
    const termData = EQUATION_TERMS[termKey];
    if (!termData) return;

    // Highlight active in DOM
    this.container.querySelectorAll('.math-clickable').forEach(el => {
      el.classList.toggle('active-term', el.getAttribute('data-term') === termKey);
    });

    const box = this.container.querySelector('#term-detail-box');
    if (!box) return;

    box.innerHTML = `
      <div class="term-card-body animate-fade-in">
        <div class="term-header-line">
          <div class="term-symbol-badge" id="term-badge-tex"></div>
          <div class="term-title-block">
            <h4>${termData.name}</h4>
            <span class="term-coupling-tag">${termData.coupling}</span>
          </div>
        </div>

        <div class="term-meta-grid">
          <div class="meta-item">
            <span class="meta-label">Physical Meaning:</span>
            <p class="meta-val">${termData.meaning}</p>
          </div>
          <div class="meta-item">
            <span class="meta-label">SI Units:</span>
            <span class="meta-val mono">${termData.units}</span>
          </div>
          <div class="meta-item">
            <span class="meta-label">Typical Values & Magnitude:</span>
            <span class="meta-val">${termData.typical}</span>
          </div>
        </div>
      </div>
    `;

    const badgeTex = box.querySelector('#term-badge-tex');
    if (badgeTex && window.katex) {
      window.katex.render(termData.symbol, badgeTex, { throwOnError: false, displayMode: true });
    }
  }
}
